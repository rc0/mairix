# published by the Free Software Foundation.
#
# Usage:
#   python3 gen_utf8_fold_table.py CaseFolding.txt > utf8fold_table.h
#
# CaseFolding.txt is part of the Unicode Character Database.  The table
# checked into the repository was generated from Unicode 16.0.0:
#
#   https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt
#
# Only the simple case folding mappings (statuses C and S in
# CaseFolding.txt) are used, and only those whose folded form has the
# same UTF-8 encoded length as the original character.  utf8fold.c
# folds strings in place, so a mapping that would change the byte
# length (e.g. U+212A KELVIN SIGN -> 'k') cannot be applied; such
# characters are deliberately left unchanged, symmetrically, both when
# indexing and when searching.  Full foldings (status F, e.g.
# U+00DF -> "ss") are never used: this is simple case folding, not
# full case folding, so U+00DF and U+0130 have no mapping at all.

import sys


def utf8_len(cp):
    if cp < 0x80:
        return 1
    if cp < 0x800:
        return 2
    if cp < 0x10000:
        return 3
    return 4


def read_mappings(path):
    """Return sorted list of (src, dst) simple, length-preserving folds."""
    mappings = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(";")]
            if len(fields) < 3:
                continue
            src = int(fields[0], 16)
            status = fields[1]
            if status not in ("C", "S"):
                continue
            targets = fields[2].split()
            if len(targets) != 1:
                continue
            dst = int(targets[0], 16)
            if dst == src:
                continue
            if utf8_len(dst) != utf8_len(src):
                continue
            mappings[src] = dst
    return sorted(mappings.items())


def compress(mappings):
    """Split mappings into constant-delta ranges and individual pairs.

    A range is a run of at least two source code points, evenly spaced
    (step 1, or step 2 for the many scripts whose upper/lowercase
    letters alternate in the code charts), whose (dst - src) delta is
    constant.  Everything else is a pair.
    """
    ranges = []
    rest = []
    i = 0
    while i < len(mappings):
        src, dst = mappings[i]
        delta = dst - src
        j = i
        while (j + 1 < len(mappings)
               and mappings[j + 1][0] == mappings[j][0] + 1
               and mappings[j + 1][1] - mappings[j + 1][0] == delta):
            j += 1
        if j > i:
            ranges.append((mappings[i][0], mappings[j][0], 1, delta))
            i = j + 1
        else:
            rest.append(mappings[i])
            i += 1

    pairs = []
    i = 0
    while i < len(rest):
        src, dst = rest[i]
        delta = dst - src
        j = i
        while (j + 1 < len(rest)
               and rest[j + 1][0] == rest[j][0] + 2
               and rest[j + 1][1] - rest[j + 1][0] == delta):
            j += 1
        if j > i:
            ranges.append((rest[i][0], rest[j][0], 2, delta))
            i = j + 1
        else:
            pairs.append(rest[i])
            i += 1

    ranges.sort()
    return ranges, pairs


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_utf8_fold_table.py CaseFolding.txt")
    mappings = read_mappings(sys.argv[1])
    ranges, pairs = compress(mappings)

    out = sys.stdout
    out.write("/* utf8fold_table.h - Unicode simple case folding table.\n")
    out.write(" *\n")
    out.write(" * GENERATED by gen_utf8_fold_table.py from the Unicode\n")
    out.write(" * Character Database (CaseFolding.txt, Unicode 16.0.0),\n")
    out.write(" * statuses C and S, restricted to mappings whose folded\n")
    out.write(" * form has the same UTF-8 encoded length as the original.\n")
    out.write(" * Do not edit this file by hand; regenerate it instead.\n")
    out.write(" */\n\n")
    out.write("struct utf8_fold_range {\n")
    out.write("  unsigned long first; /* first code point of the range */\n")
    out.write("  unsigned long last;  /* last code point of the range */\n")
    out.write("  unsigned long step;  /* spacing of covered code points */\n")
    out.write("  long delta;          /* folded = original + delta */\n")
    out.write("};\n\n")
    out.write("struct utf8_fold_pair {\n")
    out.write("  unsigned long from;\n")
    out.write("  unsigned long to;\n")
    out.write("};\n\n")

    out.write("static const struct utf8_fold_range utf8_fold_ranges[] = {\n")
    for first, last, step, delta in ranges:
        out.write("  { 0x%04lX, 0x%04lX, %lu, %ld },\n"
                  % (first, last, step, delta))
    out.write("};\n\n")

    out.write("static const struct utf8_fold_pair utf8_fold_pairs[] = {\n")
    for src, dst in pairs:
        out.write("  { 0x%04lX, 0x%04lX },\n" % (src, dst))
    out.write("};\n")

    sys.stderr.write("gen_utf8_fold_table: %d mappings, %d ranges, %d pairs\n"
                     % (len(mappings), len(ranges), len(pairs)))


if __name__ == "__main__":
    main()
