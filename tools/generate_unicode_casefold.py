#!/usr/bin/env python3
"""Generate the byte-length-preserving Unicode case-fold table for mairix."""

from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "utf8fold_table.inc"


def mappings() -> list[tuple[int, int]]:
    result: list[tuple[int, int]] = []
    for codepoint in range(0x110000):
        if 0xD800 <= codepoint <= 0xDFFF:
            continue
        source = chr(codepoint)
        folded = source.casefold()
        if len(folded) != 1 or folded == source:
            continue
        target = ord(folded)
        if len(source.encode("utf-8")) != len(folded.encode("utf-8")):
            continue
        result.append((codepoint, target))
    return result


def compress(items: list[tuple[int, int]]) -> tuple[
    list[tuple[int, int, int, int]], list[tuple[int, int]]
]:
    ranges: list[tuple[int, int, int, int]] = []
    pairs: list[tuple[int, int]] = []
    index = 0
    while index < len(items):
        if index + 2 < len(items):
            step = items[index + 1][0] - items[index][0]
            delta = items[index][1] - items[index][0]
            end = index + 1
            while (
                end + 1 < len(items)
                and items[end + 1][0] - items[end][0] == step
                and items[end + 1][1] - items[end + 1][0] == delta
            ):
                end += 1
            if end - index + 1 >= 3:
                ranges.append((items[index][0], items[end][0], step, delta))
                index = end + 1
                continue
        pairs.append(items[index])
        index += 1
    return ranges, pairs


def render() -> str:
    ranges, pairs = compress(mappings())
    lines = [
        "/* Generated by tools/generate_unicode_casefold.py.",
        f" * Unicode database version: {unicodedata.unidata_version}",
        " * Includes one-code-point folds that preserve UTF-8 byte length.",
        " */",
        "",
        "static const struct fold_range fold_ranges[] = {",
    ]
    lines.extend(
        f"  {{ 0x{first:06X}u, 0x{last:06X}u, {step}u, {delta:+d} }},"
        for first, last, step, delta in ranges
    )
    lines.extend(["};", "", "static const struct fold_pair fold_pairs[] = {"])
    lines.extend(
        f"  {{ 0x{source:06X}u, 0x{target:06X}u }}," for source, target in pairs
    )
    lines.extend([
        "};",
        "",
        "#define FOLD_RANGE_COUNT (sizeof(fold_ranges) / sizeof(fold_ranges[0]))",
        "#define FOLD_PAIR_COUNT (sizeof(fold_pairs) / sizeof(fold_pairs[0]))",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("output", nargs="?", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    expected = render()
    output = args.output.resolve()
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != expected:
            print(f"{output} is not up to date", file=sys.stderr)
            return 1
        print(f"{output} is up to date")
        return 0
    output.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
