/* UTF-8 aware helpers for tokenisation and case folding.
 *
 * mairix indexes and searches raw bytes.  Multibyte UTF-8 sequences are
 * kept in tokens, but they have to be handled as whole characters in two
 * places :
 *
 *   - tokenisation : punctuation, separators, symbols and formatting
 *     characters are not part of words, so e.g. "«café»" tokenises to
 *     "café".  Bytes that are not a well-formed UTF-8 sequence keep the
 *     historical behaviour of being treated as word characters, so text
 *     in non-UTF-8 8-bit encodings remains searchable as before.
 *
 *   - canonicalisation : tokens and search words are lowercased so that
 *     matching is case-insensitive.  This is extended to Unicode simple
 *     case folding (CaseFolding.txt, common and simple mappings), so
 *     "s:CAFÉ" finds a message indexed under "Café".  Mappings that
 *     expand to several code points (e.g. ß -> "ss") are not simple
 *     folds and are left alone.
 *
 * The tables below are generated by tools/generate_unicode_tables.py
 * (Unicode 15.1.0); regenerate with that script, do not edit by hand. */

#include "mairix.h"

int utf8_decode_char(const char *s, unsigned long *cp)/*{{{*/
{
  const unsigned char *u = (const unsigned char *) s;
  unsigned long v;
  int len, i;

  if (u[0] < 0x80) {
    *cp = u[0];
    return 1;
  } else if (u[0] < 0xc2) {
    /* Stray continuation byte or overlong lead byte */
    return 0;
  } else if (u[0] < 0xe0) {
    v = u[0] & 0x1f; len = 2;
  } else if (u[0] < 0xf0) {
    v = u[0] & 0x0f; len = 3;
  } else if (u[0] < 0xf5) {
    v = u[0] & 0x07; len = 4;
  } else {
    return 0;
  }

  for (i = 1; i < len; i++) {
    /* A continuation byte is never NUL, so this cannot read past the
       terminating NUL of the string. */
    if ((u[i] & 0xc0) != 0x80) return 0;
    v = (v << 6) | (u[i] & 0x3f);
  }

  /* Reject overlong encodings, UTF-16 surrogates and out of range values */
  if ((len == 2 && v < 0x80)
      || (len == 3 && v < 0x800)
      || (len == 4 && v < 0x10000)
      || (v >= 0xd800 && v <= 0xdfff)
      || v > 0x10ffff) {
    return 0;
  }

  *cp = v;
  return len;
}
/*}}}*/

