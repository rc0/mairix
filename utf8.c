char *utf8_tolower_string(const char *src)/*{{{*/
{
  const unsigned char *r;
  unsigned char *out, *w;

  /* The fold of one code point is always one code point, and the UTF-8
     encoding of a folded code point is never longer than 4 bytes, so
     this bound cannot be exceeded. */
  out = (unsigned char *) Malloc(4 * strlen(src) + 1);
  r = (const unsigned char *) src;
  w = out;

  while (*r) {
    unsigned long cp;
    int len = utf8_decode_char((const char *) r, &cp);
    if (len > 0) {
      w += encode_utf8(w, fold_codepoint(cp));
      r += len;
    } else {
      /* Not a well-formed UTF-8 sequence : keep the byte so that
         non-UTF-8 text is unaffected. */
      *w++ = *r++;
    }
  }
  *w = 0;
  return (char *) out;
}
