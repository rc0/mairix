int utf8_word_char_p(unsigned long cp)/*{{{*/
{
  int lo, hi, mid;

  lo = 0; hi = N_DELIM_RANGES;
  while (lo < hi) {
    mid = lo + ((hi - lo) >> 1);
    if (cp < delim_ranges[mid].first) {
      hi = mid;
    } else if (cp > delim_ranges[mid].last) {
      lo = mid + 1;
    } else {
      return 0;
    }
  }
  return 1;
}
/*}}}*/

