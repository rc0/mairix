static int encode_utf8(unsigned char *out, unsigned long cp)/*{{{*/
{
  if (cp < 0x80) {
    out[0] = cp;
    return 1;
  } else if (cp < 0x800) {
    out[0] = 0xc0 | (cp >> 6);
    out[1] = 0x80 | (cp & 0x3f);
    return 2;
  } else if (cp < 0x10000) {
    out[0] = 0xe0 | (cp >> 12);
    out[1] = 0x80 | ((cp >> 6) & 0x3f);
    out[2] = 0x80 | (cp & 0x3f);
    return 3;
  } else {
    out[0] = 0xf0 | (cp >> 18);
    out[1] = 0x80 | ((cp >> 12) & 0x3f);
    out[2] = 0x80 | ((cp >> 6) & 0x3f);
    out[3] = 0x80 | (cp & 0x3f);
    return 4;
  }
}
