#define N_FOLD_PAIRS (sizeof(fold_pairs) / sizeof(fold_pairs[0]))

static unsigned long fold_codepoint(unsigned long cp)/*{{{*/
{
  int lo, hi, mid;

  lo = 0; hi = N_FOLD_RANGES;
  while (lo < hi) {
    mid = lo + ((hi - lo) >> 1);
    if (cp < fold_ranges[mid].first) {
      hi = mid;
    } else if (cp > fold_ranges[mid].last) {
      lo = mid + 1;
    } else {
      return ((cp - fold_ranges[mid].first) % fold_ranges[mid].step)
        ? cp : cp + fold_ranges[mid].delta;
    }
  }

  lo = 0; hi = N_FOLD_PAIRS;
  while (lo < hi) {
    mid = lo + ((hi - lo) >> 1);
    if (cp < fold_pairs[mid].from) {
      hi = mid;
    } else if (cp > fold_pairs[mid].from) {
      lo = mid + 1;
    } else {
      return fold_pairs[mid].to;
    }
  }

  return cp;
}
