/* Unicode simple case folding and delimiter detection for UTF-8 text.
 *
 * All tokens stored in the database and all query words are passed through
 * fold_utf8_inplace() so that both sides of a comparison see identical bytes.
 * ASCII has always been folded this way; this module extends the same
 * symmetry to non-ASCII ranges (Latin-1 Supplement, Latin Extended-A/B,
 * Latin Extended Additional, Greek and Coptic, Cyrillic, and Armenian).
 *
 * Additionally, utf8_is_delimiter() identifies Unicode punctuation, quotes,
 * em-dashes, and non-breaking spaces so that words within quotes or around
 * dashes tokenize cleanly rather than being corrupted into composite tokens.
 */

