/* Look up the folded form of a code point; returns cp unchanged if unmapped. */
static unsigned short fold_char(unsigned int cp)
{
  unsigned int lo = 0, hi = sizeof(fold_ranges)/sizeof(fold_ranges[0]);
  while (lo < hi) {
    unsigned int mid = (lo + hi) / 2;
    if (cp < fold_ranges[mid].lo) hi = mid;
    else if (cp > fold_ranges[mid].hi) lo = mid + 1;
    else return (unsigned short)(cp + fold_ranges[mid].delta);
  }
  {
    unsigned int a = 0, b = sizeof(fold_pairs)/sizeof(fold_pairs[0]);
    while (a < b) {
      unsigned int mid = (a + b) / 2;
      if (fold_pairs[mid].from < cp) a = mid + 1;
      else if (fold_pairs[mid].from > cp) b = mid;
      else return fold_pairs[mid].to;
    }
  }
  return (unsigned short)cp;
}

int utf8_is_delimiter(unsigned int cp)
{
  /* Non-breaking space & section sign */
  if (cp == 0x00A0 || cp == 0x00A7) return 1;
  /* Guillemets « and » */
  if (cp == 0x00AB || cp == 0x00BB) return 1;
  /* Unicode spaces (U+2000 to U+200B) */
  if (cp >= 0x2000 && cp <= 0x200B) return 1;
  /* Hyphens and dashes: hyphen, non-breaking hyphen, figure dash, en-dash, em-dash, horizontal bar */
  if (cp >= 0x2010 && cp <= 0x2015) return 1;
  /* Quotation marks: single/double curved quotes, low-9 quotes */
  if (cp >= 0x2018 && cp <= 0x201F) return 1;
  /* Bullets and ellipsis */
  if (cp == 0x2022 || cp == 0x2026 || cp == 0x25E6) return 1;
  /* Narrow NBSP, math space, ideographic space, BOM */
  if (cp == 0x202F || cp == 0x205F || cp == 0x3000 || cp == 0xFEFF) return 1;
  /* CJK punctuation & brackets */
  if (cp >= 0x3001 && cp <= 0x3003) return 1;
  if (cp >= 0x3008 && cp <= 0x3011) return 1;
  /* Fullwidth ASCII symbols and punctuation */
  if (cp >= 0xFF01 && cp <= 0xFF0F) return 1;
  if (cp >= 0xFF1A && cp <= 0xFF20) return 1;
  if (cp >= 0xFF3B && cp <= 0xFF40) return 1;
  if (cp >= 0xFF5B && cp <= 0xFF65) return 1;

  return 0;
}

void fold_utf8_inplace(char *str)
{
  unsigned char *p = (unsigned char *) str;

  if (!p) return;
  while (*p) {
    unsigned char c = *p;
    if (c < 0x80) {
      unsigned int n = 0;
      while (p[n] < 0x80 && p[n]) n++; /* fold runs of ASCII in one go */
      for (; n; n--, p++) {
        if ((*p >= 'A') && (*p <= 'Z')) *p = *p + ('a' - 'A');
      }
    } else if ((c >= 0xC2) && (c <= 0xDF) && ((p[1] & 0xC0) == 0x80)) {
      /* 2-byte sequence: U+0080..U+07FF (Latin-1, Latin Ext-A/B, Greek, Cyrillic, Armenian) */
      unsigned int cp = ((unsigned int)(c & 0x1f) << 6) | (p[1] & 0x3f);
      unsigned int fc = fold_char(cp);
      if (fc != cp) {
        p[0] = 0xc0 | (fc >> 6);
        p[1] = 0x80 | (fc & 0x3f);
      }
      p += 2;
    } else if ((c >= 0xE0) && (c <= 0xEF) && ((p[1] & 0xC0) == 0x80) && ((p[2] & 0xC0) == 0x80)) {
      /* 3-byte sequence: U+0800..U+FFFF (Latin Extended Additional) */
      unsigned int cp = ((unsigned int)(c & 0x0f) << 12) | ((unsigned int)(p[1] & 0x3f) << 6) | (p[2] & 0x3f);
      unsigned int fc = fold_char(cp);
      if (fc != cp) {
        p[0] = 0xe0 | (fc >> 12);
        p[1] = 0x80 | ((fc >> 6) & 0x3f);
        p[2] = 0x80 | (fc & 0x3f);
      }
      p += 3;
    } else {
      /* invalid UTF-8 or 4-byte sequence: leave bytes untouched */
      p++;
    }
  }
}
